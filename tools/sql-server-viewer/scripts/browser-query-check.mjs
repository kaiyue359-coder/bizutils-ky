import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (err) => errors.push(err.message));
await mkdir('Outputs/query-controls', { recursive: true });
try {
  await page.goto('http://127.0.0.1:5317/');
  await page.locator('.data-table tbody tr').first().waitFor();
  const choose = async (label, name) => {
    await page.getByRole('combobox', { name: label, exact: true }).click();
    await page.getByRole('option', { name, exact: true }).click();
  };
  const idle = async () => { await page.locator('.readonly-grid[aria-busy="false"]').waitFor(); };
  await idle();
  await choose('每页行数', '200');
  await page.waitForFunction(() => document.querySelectorAll('.data-table tbody tr').length === 200);
  await choose('每页行数', '500');
  await page.waitForFunction(() => document.querySelectorAll('.data-table tbody tr').length === 500);
  await page.getByLabel('页码', { exact: true }).fill('3');
  await page.getByLabel('页码', { exact: true }).press('Enter');
  await page.waitForFunction(() => document.querySelectorAll('.data-table tbody tr').length === 260);
  await page.getByRole('button', { name: '首页', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.data-table tbody tr').length === 500);
  await page.getByRole('button', { name: '多条件排序', exact: true }).click();
  await page.getByRole('button', { name: '添加排序' }).click();
  await choose('排序字段 1', 'quantity');
  await page.getByRole('button', { name: '添加排序' }).click();
  await choose('排序字段 2', 'unit_price');
  await choose('排序方向 2', '降序');
  await page.getByRole('button', { name: '应用', exact: true }).click();
  await idle();
  await page.waitForFunction(() => document.querySelector('.data-table tbody tr td:nth-child(4)')?.textContent === '1');
  const sorted = await page.locator('.data-table tbody tr').evaluateAll((rows) => rows.map((r) => [Number(r.children[3].textContent), Number(r.children[4].textContent)]));
  for (let i = 1; i < sorted.length; i++) assert.ok(sorted[i-1][0] < sorted[i][0] || (sorted[i-1][0] === sorted[i][0] && sorted[i-1][1] >= sorted[i][1]));
  await page.getByRole('button', { name: '字段筛选', exact: true }).click();
  await choose('筛选字段', 'quantity');
  await choose('筛选运算符', '大于等于');
  await page.getByPlaceholder('筛选值').fill('2');
  await page.getByRole('button', { name: '添加条件' }).click();
  await choose('筛选字段', 'unit_price');
  await choose('筛选运算符', '大于');
  await page.getByPlaceholder('筛选值').fill('25');
  await page.getByRole('button', { name: '添加条件' }).click();
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => [...document.querySelectorAll('.data-table tbody tr')].every((r) => Number(r.children[3].textContent) >= 2 && Number(r.children[4].textContent) > 25));
  await idle();
  if (await page.getByRole('button', { name: '关闭筛选', exact: true }).isVisible()) await page.getByRole('button', { name: '关闭筛选', exact: true }).click();
  const resizer = page.getByRole('separator', { name: '调整 order_id 列宽', exact: true });
  const beforeWidth = await page.locator('.data-table th').first().evaluate((el) => el.getBoundingClientRect().width);
  await resizer.focus();
  await resizer.press('ArrowRight');
  assert.ok(await page.locator('.data-table th').first().evaluate((el) => el.getBoundingClientRect().width) > beforeWidth);
  await page.getByLabel('页码', { exact: true }).fill('999');
  assert.equal(await page.getByRole('button', { name: '跳转', exact: true }).isDisabled(), true);
  await page.getByLabel('页码', { exact: true }).fill('1');
  await page.screenshot({ path: 'Outputs/query-controls/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'Outputs/query-controls/mobile.png', fullPage: true });
  await page.getByRole('button', { name: '多条件排序', exact: true }).click();
  await page.screenshot({ path: 'Outputs/query-controls/mobile-sort.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Page horizontal overflow');
  assert.deepEqual(errors, []);
  console.log('PASS: 500 rows, page jump, two-key sort, AND filters, desktop/mobile, no page errors.');
} finally { await browser.close(); }
